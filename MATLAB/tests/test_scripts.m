function test_manual_weights_render(testCase)
work    = testCase.TestData.work;
dataDir = testCase.TestData.dataDir;
cfgPath = fullfile(work, 'cfg_manual.yaml');

write_lines(cfgPath, { ...
    ['element_patterns_dir: "' dataDir '"'], ...
    'polarization: "copol"', ...
    'directives:', ...
    '  - type: "peak"', ...
    '    theta: 0.0', ...
    '    phi: 0.0', ...
    '    theta_width: 20.0', ...
    '    phi_width: 20.0', ...
    '    weight: 1.0', ...
    });

% (a) uniform weights path.
out1 = fullfile(work, 'manual_uniform.png');
m1 = manual_weights_render(cfgPath, [], out1);
verifyTrue(testCase, isfile(out1));
verifyTrue(testCase, isfinite(m1.global_peak_dbi));

% (b) weights-CSV path (run_optimization format: element_index,amplitude,phase_deg,real,imag).
csvPath = fullfile(work, 'weights.csv');
fid = fopen(csvPath, 'w');
fprintf(fid, 'element_index,amplitude,phase_deg,real,imag\n');
for n = 0:15
    fprintf(fid, '%d,%.2f,%.2f,%.2f,%.2f\n', n, 1.0, 0.0, 1.0, 0.0);
end
fclose(fid);

out2 = fullfile(work, 'manual_csv.png');
m2 = manual_weights_render(cfgPath, csvPath, out2);
verifyTrue(testCase, isfile(out2));
verifyTrue(testCase, isfinite(m2.global_peak_dbi));
end
